-- FleetTrack relational model (PostgreSQL 16), designed to 3NF.

CREATE TABLE IF NOT EXISTS customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code VARCHAR(20) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE,
    phone VARCHAR(24),
    city VARCHAR(80) NOT NULL,
    state VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hubs (
    hub_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hub_code VARCHAR(12) NOT NULL UNIQUE,
    hub_name VARCHAR(100) NOT NULL,
    city VARCHAR(80) NOT NULL,
    state VARCHAR(80) NOT NULL,
    daily_capacity INTEGER NOT NULL CHECK (daily_capacity > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS vehicles (
    vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_no VARCHAR(24) NOT NULL UNIQUE,
    vehicle_type VARCHAR(30) NOT NULL CHECK (vehicle_type IN ('van', 'mini_truck', 'truck', 'container')),
    capacity_kg NUMERIC(10,2) NOT NULL CHECK (capacity_kg > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS drivers (
    driver_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_code VARCHAR(20) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    license_no VARCHAR(32) NOT NULL UNIQUE,
    phone VARCHAR(24),
    hire_date DATE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS routes (
    route_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_code VARCHAR(20) NOT NULL UNIQUE,
    route_name VARCHAR(160) NOT NULL UNIQUE,
    origin_hub_id BIGINT NOT NULL REFERENCES hubs(hub_id),
    destination_hub_id BIGINT NOT NULL REFERENCES hubs(hub_id),
    distance_km NUMERIC(10,2) NOT NULL CHECK (distance_km > 0),
    CHECK (origin_hub_id <> destination_hub_id)
);

CREATE TABLE IF NOT EXISTS shipments (
    shipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_number VARCHAR(32) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    route_id BIGINT NOT NULL REFERENCES routes(route_id),
    assigned_vehicle_id BIGINT REFERENCES vehicles(vehicle_id),
    assigned_driver_id BIGINT REFERENCES drivers(driver_id),
    weight_kg NUMERIC(10,2) NOT NULL CHECK (weight_kg > 0),
    shipping_cost NUMERIC(12,2) NOT NULL CHECK (shipping_cost >= 0),
    priority VARCHAR(12) NOT NULL DEFAULT 'standard' CHECK (priority IN ('standard', 'express', 'same_day')),
    booked_at TIMESTAMPTZ NOT NULL,
    expected_delivery_at TIMESTAMPTZ NOT NULL,
    delivered_at TIMESTAMPTZ,
    status VARCHAR(24) NOT NULL DEFAULT 'booked'
        CHECK (status IN ('booked', 'picked_up', 'in_transit', 'at_hub', 'out_for_delivery', 'delivered', 'failed', 'exception', 'returned', 'cancelled')),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (expected_delivery_at >= booked_at),
    CHECK (delivered_at IS NULL OR delivered_at >= booked_at)
);

CREATE TABLE IF NOT EXISTS deliveries (
    delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL REFERENCES shipments(shipment_id) ON DELETE CASCADE,
    attempt_no SMALLINT NOT NULL CHECK (attempt_no > 0),
    delivery_status VARCHAR(24) NOT NULL CHECK (delivery_status IN ('delivered', 'failed', 'out_for_delivery', 'exception')),
    attempted_at TIMESTAMPTZ NOT NULL,
    recipient_name VARCHAR(120),
    failure_reason VARCHAR(240),
    notes TEXT,
    UNIQUE (shipment_id, attempt_no),
    CHECK (delivery_status <> 'delivered' OR recipient_name IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS shipment_status_history (
    status_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL REFERENCES shipments(shipment_id) ON DELETE CASCADE,
    status VARCHAR(24) NOT NULL
        CHECK (status IN ('booked', 'picked_up', 'in_transit', 'at_hub', 'out_for_delivery', 'delivered', 'failed', 'exception', 'returned', 'cancelled')),
    hub_id BIGINT REFERENCES hubs(hub_id),
    event_at TIMESTAMPTZ NOT NULL,
    notes TEXT,
    source VARCHAR(24) NOT NULL DEFAULT 'system' CHECK (source IN ('system', 'operator', 'seed', 'delivery')),
    event_key VARCHAR(120)
);

ALTER TABLE shipment_status_history
    ADD COLUMN IF NOT EXISTS event_key VARCHAR(120);

CREATE INDEX IF NOT EXISTS idx_shipments_booked_at ON shipments(booked_at);
CREATE INDEX IF NOT EXISTS idx_shipments_status ON shipments(status);
CREATE INDEX IF NOT EXISTS idx_shipments_route ON shipments(route_id);
CREATE INDEX IF NOT EXISTS idx_history_shipment_time ON shipment_status_history(shipment_id, event_at DESC);
CREATE INDEX IF NOT EXISTS idx_history_hub_time ON shipment_status_history(hub_id, event_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_history_event_key ON shipment_status_history(event_key)
    WHERE event_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_deliveries_shipment_attempt ON deliveries(shipment_id, attempt_no DESC);

-- Serialize shipment events before their inserts and derive current state from canonical history.
CREATE OR REPLACE FUNCTION fn_lock_shipment_for_event()
RETURNS TRIGGER AS $$
BEGIN
    PERFORM 1
      FROM shipments
     WHERE shipment_id = NEW.shipment_id
     FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Shipment % does not exist', NEW.shipment_id
            USING ERRCODE = 'foreign_key_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_lock_shipment_for_status_event ON shipment_status_history;
CREATE TRIGGER trg_lock_shipment_for_status_event
BEFORE INSERT ON shipment_status_history
FOR EACH ROW EXECUTE FUNCTION fn_lock_shipment_for_event();

DROP TRIGGER IF EXISTS trg_lock_shipment_for_delivery ON deliveries;
CREATE TRIGGER trg_lock_shipment_for_delivery
BEFORE INSERT OR UPDATE OF shipment_id ON deliveries
FOR EACH ROW EXECUTE FUNCTION fn_lock_shipment_for_event();

-- event_at is authoritative; status_history_id deterministically breaks timestamp ties.
CREATE OR REPLACE FUNCTION fn_apply_shipment_status_event()
RETURNS TRIGGER AS $$
BEGIN
    WITH canonical AS (
        SELECT h.status
          FROM shipment_status_history h
         WHERE h.shipment_id = NEW.shipment_id
         ORDER BY h.event_at DESC, h.status_history_id DESC
         LIMIT 1
    ),
    first_delivery AS (
        SELECT MIN(h.event_at) AS delivered_at
          FROM shipment_status_history h
         WHERE h.shipment_id = NEW.shipment_id
           AND h.status = 'delivered'
    )
    UPDATE shipments s
       SET status = canonical.status,
           delivered_at = COALESCE(s.delivered_at, first_delivery.delivered_at)
      FROM canonical
      CROSS JOIN first_delivery
     WHERE s.shipment_id = NEW.shipment_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_apply_shipment_status_event ON shipment_status_history;
CREATE TRIGGER trg_apply_shipment_status_event
AFTER INSERT ON shipment_status_history
FOR EACH ROW EXECUTE FUNCTION fn_apply_shipment_status_event();

-- Delivery events are keyed by delivery attempt and status so retries are idempotent.
CREATE OR REPLACE FUNCTION fn_log_delivery_attempt()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO shipment_status_history
        (shipment_id, status, event_at, notes, source, event_key)
    VALUES (NEW.shipment_id, NEW.delivery_status, NEW.attempted_at,
            COALESCE(NEW.notes, 'Delivery attempt recorded'), 'delivery',
            format(
                'delivery:%s:%s:%s',
                NEW.delivery_id,
                NEW.delivery_status,
                EXTRACT(EPOCH FROM NEW.attempted_at)::numeric
            ))
    ON CONFLICT (event_key) WHERE event_key IS NOT NULL DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_log_delivery_attempt ON deliveries;
CREATE TRIGGER trg_log_delivery_attempt
AFTER INSERT OR UPDATE OF delivery_status ON deliveries
FOR EACH ROW EXECUTE FUNCTION fn_log_delivery_attempt();

-- View: one row per shipment with dimensions and SLA outcome.
CREATE OR REPLACE VIEW vw_delivery_performance AS
SELECT
    s.shipment_id,
    s.tracking_number,
    s.status,
    c.customer_code,
    c.full_name AS customer_name,
    r.route_code,
    r.route_name,
    r.distance_km,
    oh.hub_name AS origin_hub,
    dh.hub_name AS destination_hub,
    d.driver_code,
    d.full_name AS driver_name,
    v.registration_no,
    s.weight_kg,
    s.shipping_cost,
    s.priority,
    s.booked_at,
    s.expected_delivery_at,
    s.delivered_at,
    CASE
        WHEN s.delivered_at IS NULL THEN NULL
        ELSE (s.delivered_at <= s.expected_delivery_at)
    END AS on_time,
    CASE
        WHEN s.delivered_at IS NULL THEN NULL
        ELSE ROUND((EXTRACT(EPOCH FROM (s.delivered_at - s.booked_at)) / 3600.0)::numeric, 2)
    END AS transit_hours
FROM shipments s
JOIN customers c ON c.customer_id = s.customer_id
JOIN routes r ON r.route_id = s.route_id
JOIN hubs oh ON oh.hub_id = r.origin_hub_id
JOIN hubs dh ON dh.hub_id = r.destination_hub_id
LEFT JOIN drivers d ON d.driver_id = s.assigned_driver_id
LEFT JOIN vehicles v ON v.vehicle_id = s.assigned_vehicle_id;

-- View: operational scan volume by hub and day.
CREATE OR REPLACE VIEW vw_hub_load_daily AS
SELECT h.hub_id, h.hub_code, h.hub_name, h.city,
       date_trunc('day', sh.event_at)::date AS activity_date,
       COUNT(*) AS scan_count,
       COUNT(*) FILTER (WHERE sh.status IN ('failed', 'exception')) AS issue_scan_count
FROM shipment_status_history sh
JOIN hubs h ON h.hub_id = sh.hub_id
GROUP BY h.hub_id, h.hub_code, h.hub_name, h.city, date_trunc('day', sh.event_at)::date;

-- Authentication and authorization support tables; the eight operational tables remain unchanged.
CREATE TABLE IF NOT EXISTS roles (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(16) NOT NULL UNIQUE CHECK (role_name IN ('ADMIN', 'USER'))
);

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL CHECK (username = lower(username)),
    display_name VARCHAR(120) NOT NULL,
    email VARCHAR(254),
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login_at TIMESTAMPTZ,
    CHECK (username ~ '^[a-z0-9][a-z0-9._-]{2,63}$')
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_ci ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_ci ON users (lower(email))
    WHERE email IS NOT NULL;

CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    role_id SMALLINT NOT NULL REFERENCES roles(role_id),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS user_sessions (
    session_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash BYTEA NOT NULL UNIQUE,
    csrf_token_hash BYTEA NOT NULL,
    remote_address INET,
    user_agent VARCHAR(512),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS idx_user_sessions_user_expiry
    ON user_sessions(user_id, expires_at DESC);

CREATE TABLE IF NOT EXISTS login_attempts (
    login_attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    remote_address INET,
    succeeded BOOLEAN NOT NULL,
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_login_attempts_username_time
    ON login_attempts(username, attempted_at DESC);
CREATE INDEX IF NOT EXISTS idx_login_attempts_ip_time
    ON login_attempts(remote_address, attempted_at DESC)
    WHERE remote_address IS NOT NULL;

CREATE TABLE IF NOT EXISTS audit_logs (
    audit_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    action VARCHAR(80) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id VARCHAR(80),
    outcome VARCHAR(16) NOT NULL CHECK (outcome IN ('success', 'denied', 'failure')),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    remote_address INET,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at
    ON audit_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_actor_time
    ON audit_logs(actor_user_id, created_at DESC);
